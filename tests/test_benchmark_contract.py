"""Synthetic unit fixtures only: NOT service responses or model performance."""
import io
import json
import unittest
from PIL import Image
from scripts.benchmark_contract import (decisions_payload, vision_payload, normalise_decisions,
    normalise_vision, validate_split, evaluate_independent_tyres)


class BenchmarkContractTests(unittest.TestCase):
    def image(self):
        output = io.BytesIO()
        Image.new('RGB', (12, 12), 'red').save(output, format='JPEG')
        return output.getvalue()

    def test_request_has_no_case_metadata_and_has_image(self):
        for builder in (decisions_payload, vision_payload):
            payload = builder(self.image(), 'test-deployment', multi_question=True)
            wire = json.dumps(payload)
            self.assertIn('data:image/jpeg;base64,', wire)
            self.assertNotIn('TWI/', wire)
            self.assertNotIn('confidence', wire)
            self.assertNotIn('reason', wire)
            self.assertNotIn('filename', wire)
        self.assertEqual(len(decisions_payload(self.image(), 'test')['questions']), 1)
        self.assertEqual(len(decisions_payload(self.image(), 'test', True)['questions']), 3)

    def test_probability_policy_and_refusal_fail_closed(self):
        choice = {'type':'choice', 'name':'condition', 'choice':'good',
                  'probabilities':[{'value':'good','probability':.8}, {'value':'bad','probability':.1}, {'value':'review','probability':.1}]}
        self.assertEqual(normalise_decisions([choice], .9)['prediction'], 'review')
        self.assertEqual(normalise_decisions([choice], .7)['prediction'], 'good')
        self.assertEqual(normalise_decisions([choice], .7, .8)['prediction'], 'review')
        self.assertEqual(normalise_decisions([{'type':'refusal','name':'condition'}], .7)['prediction'], 'review')
        self.assertEqual(normalise_decisions([dict(choice, probabilities=[])], .7)['prediction'], 'review')
        self.assertEqual(normalise_decisions(None, .7)['prediction'], 'review')
        self.assertEqual(normalise_decisions([choice, choice], .7)['prediction'], 'review')
        self.assertEqual(normalise_decisions([dict(choice, name=[])], .7)['prediction'], 'review')
        invalid = dict(choice, probabilities=[{'value': [], 'probability': 1}, {'value':'bad','probability':0}, {'value':'review','probability':0}])
        self.assertEqual(normalise_decisions([invalid], .7)['prediction'], 'review')

    def test_vision_visibility_and_physical_claim_gates(self):
        result = {'visual_condition':'good', 'visibility':'adequate', 'visible_damage':'no',
                  'needs_review':False, 'evidence':'Synthetic fixture', 'tread_depth_mm':None, 'twi_verified':None}
        self.assertEqual(normalise_vision(result)['prediction'], 'good')
        self.assertEqual(normalise_vision(dict(result, visibility='inadequate'))['prediction'], 'review')
        self.assertEqual(normalise_vision(dict(result, tread_depth_mm=3))['prediction'], 'review')
        self.assertEqual(normalise_vision({})['prediction'], 'review')
        self.assertEqual(normalise_vision(dict(result, visible_damage='yes'))['prediction'], 'review')

    def test_split_group_and_hash_leakage(self):
        clean = [{'tyre_group_id':'tyre-a', 'sha256':'hash-a', 'split':'train'},
                 {'tyre_group_id':'tyre-b', 'sha256':'hash-b', 'split':'test'}]
        self.assertFalse(validate_split(clean))
        self.assertTrue(validate_split([*clean, dict(clean[0], split='test')]))
        self.assertTrue(validate_split([{'split':'test'}]))

    def test_metrics_count_abstentions_and_unsafe_clearance(self):
        # Synthetic 4-tyre fixture: no result here was generated by a model.
        rows = [{'tyre_id':'a', 'truth':'bad', 'prediction':'good'},
                {'tyre_id':'b', 'truth':'bad', 'prediction':'review'},
                {'tyre_id':'c', 'truth':'good', 'prediction':'good'},
                {'tyre_id':'d', 'truth':'review', 'prediction':'review'}]
        m = evaluate_independent_tyres(rows)
        self.assertEqual(m['tyre_count'], 4)
        self.assertEqual(m['unsafe_clearance_rate_all_bad'], .5)
        self.assertEqual(m['binary_false_negative_rate_accepted_bad'], 1)
        self.assertAlmostEqual(m['coverage'], 2/3)
        self.assertEqual(m['accepted_binary_accuracy'], .5)
        with self.assertRaises(ValueError):
            evaluate_independent_tyres([rows[0], rows[0]])
        all_review = evaluate_independent_tyres([{'tyre_id':'a', 'truth':'bad', 'prediction':'review'}])
        self.assertIsNone(all_review['accepted_binary_accuracy'])
        self.assertEqual(all_review['coverage'], 0)


if __name__ == '__main__':
    unittest.main()
